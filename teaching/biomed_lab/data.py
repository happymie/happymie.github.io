"""Small, explicitly synthetic datasets stored as inspectable SQLite files.

Every specimen is independently generated. Splits use disjoint specimen seeds;
augmentations and noisy views stay attached to their source specimen. No human,
medical or proprietary data is embedded. Coordinates and intensities are
dimensionless. These are mechanism exercises, not benchmark datasets.
"""
from __future__ import annotations

import hashlib
import io
import json
import sqlite3
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
DATA_VERSION = "synthetic-v1"
SPLITS = {"train": 16, "validation": 4, "test": 4}
KINDS = {
    "01": "shapes2d", "02": "phantoms3d", "03": "waves",
    "04": "shapes2d", "05": "shapes2d", "06": "prompt_shapes",
    "07": "image_text", "08": "patch_bags", "09": "phantoms3d",
    "10": "shapes2d", "11": "inverse_phantoms", "12": "noisy_shapes",
    "13": "registration_pairs", "14": "field_samples", "15": "graphs",
    "16": "waves",
}


def catalog():
    return json.loads((ROOT / "catalog.json").read_text(encoding="utf-8"))["models"]


def shape_sample(seed: int, size: int = 32) -> dict[str, np.ndarray]:
    rng = np.random.default_rng(seed)
    y, x = np.mgrid[-1:1:complex(size), -1:1:complex(size)]
    cx, cy = rng.uniform(-0.25, 0.25, 2)
    r = rng.uniform(0.3, 0.55)
    label = int(rng.integers(0, 3))
    if label == 0:
        foreground = (x - cx)**2 + (y - cy)**2 < r*r
    elif label == 1:
        foreground = np.maximum(np.abs(x - cx), np.abs(y - cy)) < r
    else:
        foreground = np.abs(x - cx) + np.abs(y - cy) < r * 1.3
    clean = (0.12 + 0.08*(x + 1)/2 + rng.uniform(0.5, 0.65)*foreground).astype("float32")
    # Independent, unclipped Gaussian views preserve E[noisy | clean] = clean.
    noise_a = rng.normal(0, 0.08, clean.shape).astype("float32")
    noise_b = rng.normal(0, 0.08, clean.shape).astype("float32")
    return {"clean": clean[None], "noise_a": noise_a[None], "noise_b": noise_b[None],
            "mask": foreground.astype("uint8"), "label": np.asarray(label, dtype="int64")}


def make_sample(seed: int, kind: str):
    data = shape_sample(seed)
    rng = np.random.default_rng(seed + 311)
    if kind in {"phantoms3d", "registration_pairs", "field_samples"}:
        z, y, x = np.mgrid[-1:1:16j, -1:1:16j, -1:1:16j]
        axes = rng.uniform(0.35, 0.7, 3)
        center = rng.uniform(-0.15, 0.15, 3)
        mask = sum(((a-c)/r)**2 for a,c,r in zip((x,y,z),center,axes)) < 1
        data["volume"] = (0.1 + mask*0.7).astype("float32")[None]
        data["volume_mask"] = mask.astype("uint8")
        points = rng.uniform(-1, 1, (32,3)).astype("float32")
        data["points"] = points
        data["point_labels"] = (np.sum(((points-center)/axes)**2, axis=-1)<1).astype("int64")
    if kind in {"waves", "image_text", "patch_bags"}:
        label = int(data["label"])
        t = np.linspace(0, 1, 64, endpoint=False)
        phase = rng.uniform(0, 2*np.pi)
        data["sequence"] = np.stack([np.sin(2*np.pi*(label+1)*t + phase + k*0.3)
                                      for k in range(4)], axis=-1).astype("float32")
        data["sequence"] += rng.normal(0,0.05,(64,4)).astype("float32")
    if kind in {"image_text", "patch_bags", "prompt_shapes"}:
        # Vocabulary: PAD=0, BOS=1, EOS=2, A=3, circle/square/diamond=4/5/6.
        data["tokens"] = np.asarray([1,3,int(data["label"])+4,2]+[0]*12,dtype="int64")
        ij = np.argwhere(data["mask"])
        data["box"] = np.asarray([ij[:,1].min(),ij[:,0].min(),ij[:,1].max(),ij[:,0].max()],dtype="float32") / 31
        data["prompt_point"] = ij[len(ij)//2, ::-1].astype("float32") / 31
    if kind == "graphs":
        # Transductive task inside each independently sampled graph.
        # Train/validation/test split the whole graph, never adjacent nodes.
        labels = rng.integers(0,3,32)
        p = np.where(labels[:,None] == labels[None,:],0.65,0.05)
        a = np.triu(rng.random((32,32)) < p,1)
        a = a | a.T
        feats = rng.normal(0,0.4,(32,8)).astype("float32")
        feats[:, :3] += np.eye(3)[labels]*0.7
        data.update(adjacency=a.astype("float32"), node_features=feats,
                    node_labels=labels.astype("int64"))
    return data


def create_database(model: dict, destination: Path | None = None):
    """Refuse to overwrite an existing file; regeneration needs a new path."""
    destination = destination or ROOT / "data" / f"{model['num']:03d}.sqlite3"
    if destination.exists():
        return destination
    destination.parent.mkdir(parents=True, exist_ok=True)
    kind = KINDS[model["family_code"]]
    metadata = {"version":DATA_VERSION, "model_num":model["num"], "model_id":model["id"],
                "title":model["title"], "kind":kind, "license":"CC0-1.0",
                "source":"Procedurally generated by biomed_lab/data.py; no clinical data",
                "coordinates":"field points: dimensionless [-1,1] (x,y,z); image box/point prompts: [0,1] (x,y); arrays volume=(C,D,H,W), image=(C,H,W)",
                "units":"dimensionless intensity; not Hounsfield units",
                "noise_storage":"Clean arrays are stored; two independent Gaussian views are regenerated deterministically from each specimen seed by shape_sample().",
                "splits":SPLITS, "limitations":"24 synthetic specimens; not clinical or benchmark evidence",
                "generator_sha256":hashlib.sha256(Path(__file__).read_bytes()).hexdigest()}
    with sqlite3.connect(destination) as con:
        con.execute("CREATE TABLE metadata (key TEXT PRIMARY KEY, value TEXT NOT NULL)")
        con.execute("CREATE TABLE samples (sample_id TEXT PRIMARY KEY, split TEXT NOT NULL, seed INTEGER UNIQUE NOT NULL, sha256 TEXT UNIQUE NOT NULL, arrays BLOB NOT NULL)")
        con.execute("CREATE INDEX sample_split ON samples(split)")
        for k,v in metadata.items():
            con.execute("INSERT INTO metadata VALUES (?,?)",(k,json.dumps(v,ensure_ascii=False)))
        offset = 0
        for split, count in SPLITS.items():
            for i in range(count):
                seed = 20261017 + model["num"]*10000 + offset+i
                data = make_sample(seed,kind)
                # Noise is an augmentation, stored by its deterministic seed.
                # Keep real clean arrays/labels in each database and avoid
                # repeating incompressible Gaussian draws 137 times.
                stored={k:v for k,v in data.items() if k not in {'noise_a','noise_b'}}
                buffer=io.BytesIO(); np.savez_compressed(buffer,**stored)
                payload = buffer.getvalue()
                con.execute("INSERT INTO samples VALUES (?,?,?,?,?)",(
                    f"{model['num']:03d}-{split}-{i:03d}",split,seed,hashlib.sha256(payload).hexdigest(),payload))
            offset += 1000
    return destination


def inspect_database(path: Path):
    # Read-only URI prevents an accidental empty DB when a path is wrong.
    with sqlite3.connect(path.resolve().as_uri()+"?mode=ro", uri=True) as con:
        metadata = {k:json.loads(v) for k,v in con.execute("SELECT key,value FROM metadata")}
        counts = dict(con.execute("SELECT split,COUNT(*) FROM samples GROUP BY split"))
        integrity = con.execute("PRAGMA integrity_check").fetchone()[0]
    return {"metadata":metadata, "counts":counts,"bytes":path.stat().st_size,"integrity":integrity}


def load_samples(path: Path, split: str):
    with sqlite3.connect(path.resolve().as_uri()+"?mode=ro", uri=True) as con:
        rows=con.execute("SELECT sample_id,seed,sha256,arrays FROM samples WHERE split=? ORDER BY sample_id",(split,)).fetchall()
    if not rows:
        raise ValueError(f"No specimens for split {split!r}")
    out=[]
    for sample_id, seed, expected, payload in rows:
        if hashlib.sha256(payload).hexdigest()!=expected:
            raise ValueError(f"Corrupt specimen {sample_id}")
        with np.load(io.BytesIO(payload),allow_pickle=False) as ar:
            sample={key:ar[key].copy() for key in ar.files}
        regenerated=shape_sample(seed)
        sample['noise_a']=regenerated['noise_a'];sample['noise_b']=regenerated['noise_b']
        out.append(sample)
    return out


def batch_from_samples(samples: list[dict], device="cpu", image_size: int=32):
    import torch
    from torch.nn import functional as F
    keys=set.intersection(*(set(x) for x in samples))
    b={k:torch.from_numpy(np.stack([s[k] for s in samples])).to(device) for k in keys}
    b["image"]=b["clean"]
    b["noisy"]=b["clean"]+b.pop("noise_a")
    b["noisy2"]=b["clean"]+b.pop("noise_b")
    b["mask"]=b["mask"].long()
    if image_size!=32:
        for k in ("image","clean","noisy","noisy2"):
            b[k]=F.interpolate(b[k],size=(image_size,image_size),mode="bilinear",align_corners=False)
        b["mask"]=F.interpolate(b["mask"][:,None].float(),size=(image_size,image_size),mode="nearest")[:,0].long()
    n=len(samples)
    # Some architectures are taught on a different modality than their family.
    # These conversions are explicit teaching inputs, never described as clinical.
    if "volume" not in b:
        b["volume"]=F.interpolate(b["clean"].unsqueeze(2),size=(16,16,16),mode="trilinear",align_corners=False)
        b["volume_mask"]=F.interpolate(b["mask"][:,None,None].float(),size=(16,16,16),mode="nearest")[:,0].long()
    else:
        b["volume_mask"]=b["volume_mask"].long()
    if "sequence" not in b:
        b["sequence"]=F.interpolate(b["clean"].mean(-2),size=64,mode="linear",align_corners=False).transpose(1,2).expand(-1,-1,4).contiguous()
    b["sequence_label"]=b["label"]
    if "tokens" not in b:
        b["tokens"]=torch.zeros(n,16,dtype=torch.long,device=device)
        b["tokens"][:,0]=1; b["tokens"][:,1]=3; b["tokens"][:,2]=b["label"]+4; b["tokens"][:,3]=2
    if "points" not in b:
        # A fixed normalized grid, no target-derived alignment/crop.
        line=torch.linspace(-1,1,32,device=device)
        b["points"]=torch.stack([line,torch.sin(3*line),torch.cos(3*line)],dim=-1)[None].expand(n,-1,-1)
    return b


def demo_batch(batch_size=2, image_size=32, device="cpu", kind="shapes2d", seed=713):
    return batch_from_samples([make_sample(seed+i,kind) for i in range(batch_size)],device,image_size)
